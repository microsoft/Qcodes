"""
Link the API documentation to the source code of QCoDeS on GitHub.

This provides the ``linkcode_resolve`` function required by ``sphinx.ext.linkcode``.
In ``conf.py``::

    extensions = [..., "sphinx.ext.linkcode"]
    linkcode_resolve = make_linkcode_resolve("microsoft/Qcodes", qcodes.__version__)
"""

from __future__ import annotations

import re
import sys
from pathlib import Path
from typing import TYPE_CHECKING

from packaging.version import Version
from sphinx.errors import PycodeError
from sphinx.pycode import ModuleAnalyzer

import qcodes

if TYPE_CHECKING:
    from collections.abc import Callable

# The directory containing the qcodes package, i.e. ``src`` in the repository.
_SOURCE_ROOT = Path(qcodes.__file__).parent.parent


def github_ref(version: str) -> str:
    """
    Return the git ref on GitHub of the source code of a version of QCoDeS.

    Args:
        version: The version of QCoDeS as generated by versioningit from git.

    Returns:
        The tag of a release (e.g. ``v0.62.0`` for ``0.62.0``), otherwise the
        commit that the version is generated from (e.g. ``76c540bef`` for
        ``0.63.0.dev12+main.g76c540bef``). Falls back to ``main`` if the version
        does not contain a commit.

    """
    parsed = Version(version)
    if parsed.local is None and not parsed.is_devrelease:
        return f"v{parsed.public}"
    for segment in reversed((parsed.local or "").split(".")):
        if re.fullmatch(r"g[0-9a-f]{7,40}", segment):
            return segment[1:]
    return "main"


def find_source(modname: str, fullname: str) -> tuple[str, int, int] | None:
    """
    Find the source code of an object documented in QCoDeS.

    The object is looked up in the module that defines it rather than in the
    module it is documented in, so an inherited member is found in its base class.

    Args:
        modname: The module the object is documented in.
        fullname: The name of the object within that module, e.g. ``Class.method``.

    Returns:
        The path of the file relative to the ``src`` directory of the repository
        and the first and last line of the definition, or None if the object is
        not a class, function or property defined in QCoDeS.

    """
    obj: object = sys.modules.get(modname)
    try:
        for part in fullname.split("."):
            obj = getattr(obj, part)
    except Exception:
        # looking up an attribute may raise anything, and instance
        # attributes cannot be looked up on the class at all
        return None
    if isinstance(obj, property):
        obj = obj.fget

    defining_modname = getattr(obj, "__module__", None)
    qualname = getattr(obj, "__qualname__", None)
    if not isinstance(defining_modname, str) or not isinstance(qualname, str):
        return None
    if defining_modname.split(".")[0] != "qcodes":
        return None

    # This is the parser that sphinx.ext.viewcode uses. It is cached per module.
    try:
        analyzer = ModuleAnalyzer.for_module(defining_modname)
        tags = analyzer.find_tags()
    except PycodeError:
        return None
    if qualname not in tags:
        return None
    _, start, end = tags[qualname]
    path = Path(analyzer.srcname).relative_to(_SOURCE_ROOT).as_posix()
    return path, start, end


def make_linkcode_resolve(
    github_repo: str, version: str
) -> Callable[[str, dict[str, str]], str | None]:
    """
    Make a ``linkcode_resolve`` function for ``sphinx.ext.linkcode``.

    Args:
        github_repo: The repository on GitHub, e.g. ``microsoft/Qcodes``.
        version: The version of QCoDeS being documented. The links point to
            the source of this version, see :func:`github_ref`.

    Returns:
        A function that returns the URL of the source on GitHub of a
        documented object, or None if it has no source in QCoDeS.

    """
    source_url = f"https://github.com/{github_repo}/blob/{github_ref(version)}/src"

    def linkcode_resolve(domain: str, info: dict[str, str]) -> str | None:
        if domain != "py":
            return None
        source = find_source(info["module"], info["fullname"])
        if source is None:
            return None
        path, start, end = source
        return f"{source_url}/{path}#L{start}-L{end}"

    return linkcode_resolve
